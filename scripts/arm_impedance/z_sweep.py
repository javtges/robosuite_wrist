"""
1-D wrist stiffness trials for insertion: the wrist's z only (out toward the keyhole = extended = soft, in toward the
base plate = contracted = stiff), held fixed through the whole insertion, over a ladder of levels and aiming errors.
Robot's arm law and FR3 gains; the mentor's wrist model and the interim calibration (measured_v0).

    cd scripts
    python -m arm_impedance.z_sweep              # 9 levels x 15 errors x 2 wrist models = 270 episodes, ~4 min on 4 workers
    python -m arm_impedance.z_sweep --quick
    python -m arm_impedance.z_figures            # -> figures/z_sweep.png

z levels are reported both as the sim's normalized z in [-1, 1] and as the HSA twist (deg) that the 11-08 sweep
measured for that plate height (wrist_calibration.normalized_z_to_twist). Metrics per episode: seated or stuck, peak
flange force, peak lateral force on the key, the wrist's lateral deflection and tilt, time from contact to seat.
"""

import argparse
import csv
import multiprocessing as mp
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import arm_impedance.evaluate as ae  # noqa: E402
from arm_impedance.wrist_calibration import WRIST_PRESETS, normalized_z_to_twist  # noqa: E402
from hsa_robots import DEFAULT_ROBOT  # noqa: E402
from key_insertion.evaluate import FIXED_LOCK, metrics  # noqa: E402
from key_insertion.oracle import KeyOracle, make_env, run_episode  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results_z")
LEVELS = np.linspace(-1.0, 1.0, 9)
ERRORS = [(dx, 0.0, dyaw) for dx in (-1.5, 0.0, 1.5) for dyaw in (0.0, 2.0, 4.0, 6.0, 8.0)]
MODELS = {"default": None, "measured_v0": WRIST_PRESETS["measured_v0"]}

_ENVS = {}


def _env(model):
    if model not in _ENVS:
        _ENVS[model] = make_env(arm="hsa", robot=DEFAULT_ROBOT, stiffness=MODELS[model], **FIXED_LOCK)
    return _ENVS[model]


def run_case(case):
    env = _env(case["model"])
    env.rng = np.random.default_rng(0)
    env.reset()
    ae.apply_gains(ae.controller(env), ae.gains())
    oracle = KeyOracle(env, wrist_z=case["z"], perception_error=(case["dx_mm"] * 1e-3, 0.0, np.radians(case["dyaw_deg"])), max_force=np.inf)
    t0 = time.time()
    try:
        result, log = run_episode(env, oracle, reset=False)
    except Exception as e:  # noqa: BLE001
        return dict(case, result="error", error=repr(e))
    row = dict(case, **metrics(result, log), wall_s=time.time() - t0)
    ins = log["phase"] >= KeyOracle.INSERT
    row["leg_k_N_m"] = float(log["leg_k"][0].mean())
    row["max_wrist_tilt_deg"] = float(np.degrees(np.abs(log["wrist_deflection"][ins, 3:5]).max())) if ins.any() else 0.0
    return row


def cases(quick=False):
    levels = LEVELS if not quick else LEVELS[::2]
    errors = ERRORS if not quick else [e for e in ERRORS if e[0] == 0.0]
    out = []
    for model in MODELS:
        for z in levels:
            for dx, _, dyaw in errors:
                out.append(dict(study="z", model=model, z=float(z), twist_deg=float(normalized_z_to_twist(z)), dx_mm=dx, dyaw_deg=dyaw))
    return out


def write_summary(rows, path):
    lines = ["# 1-D wrist stiffness (z only) for insertion", "", "Generated by `python -m arm_impedance.z_sweep`. Robot's arm law; z held fixed per episode; 15 aiming errors per level (dx ±1.5 mm × yaw 0–8°).", ""]
    for model in MODELS:
        sel = [r for r in rows if r["model"] == model and r["result"] != "error"]
        if not sel:
            continue
        lines += [f"## wrist model: {model}", "", "| z | HSA twist (deg) | leg k (N/m) | seated | yaw ≤ 2° | yaw 4° | yaw 6° | yaw 8° | peak flange (N, med) | peak lateral (N, med) | wrist lateral defl (mm, max) | contact→seat (s, med) |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for z in sorted(set(r["z"] for r in sel)):
            w = [r for r in sel if r["z"] == z]
            by = lambda cond: f"{sum(r['success'] for r in w if cond(r))}/{sum(1 for r in w if cond(r))}"  # noqa: E731
            seat = [r["contact_to_seat_s"] for r in w if r["success"] and np.isfinite(r["contact_to_seat_s"])]
            lines.append(
                f"| {z:+.2f} | {w[0]['twist_deg']:.0f} | {w[0]['leg_k_N_m']:.0f} | {sum(r['success'] for r in w)}/{len(w)} | "
                f"{by(lambda r: r['dyaw_deg'] <= 2)} | {by(lambda r: r['dyaw_deg'] == 4)} | {by(lambda r: r['dyaw_deg'] == 6)} | {by(lambda r: r['dyaw_deg'] == 8)} | "
                f"{np.median([r['peak_flange_N'] for r in w]):.1f} | {np.median([r['peak_lateral_N'] for r in w]):.1f} | {max(r['max_wrist_lateral_mm'] for r in w):.1f} | "
                f"{np.median(seat) if seat else float('nan'):.2f} |"
            )
        lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--quick", action="store_true")
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--nice", type=int, default=10)
    args = p.parse_args()
    os.nice(args.nice)
    todo = cases(args.quick)
    print(f"{len(todo)} episodes on {args.workers} workers", flush=True)
    t0 = time.time()
    rows = []
    with mp.get_context("spawn").Pool(args.workers) as pool:
        for i, row in enumerate(pool.imap_unordered(run_case, todo, chunksize=1)):
            rows.append(row)
            if (i + 1) % 25 == 0 or i + 1 == len(todo):
                print(f"  {i + 1}/{len(todo)} ({time.time() - t0:.0f} s)", flush=True)
    rows.sort(key=lambda r: (r["model"], r["z"], r["dx_mm"], r["dyaw_deg"]))
    os.makedirs(RESULTS, exist_ok=True)
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(os.path.join(RESULTS, "episodes.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v) for k, v in r.items()})
    write_summary(rows, os.path.join(RESULTS, "summary.md"))
    print(open(os.path.join(RESULTS, "summary.md")).read())


if __name__ == "__main__":
    main()
