"""
Generates robosuite/robosuite/models/assets/robots/fr3/robot.xml, the Franka Research 3 for robosuite:

- robosuite's Panda MJCF (../panda/robot.xml) for the body / joint / actuator / site / camera structure, the mount
  and the gripper attachment, so everything built for the Panda (the Stewart wrist, the controllers, the tasks) fits;
- MuJoCo Menagerie's franka_fr3 meshes and materials (meshes/, see MESHES.md) for the visual and collision geometry;
- the joint limits, torque limits and link inertials of HSA-UMI's fr3.urdf (franka_description, the values the
  robot's software enforces; Menagerie's newer franka_description limits are wider).

    cd scripts && python make_fr3_model.py

Re-run after changing any of the inputs; the output is committed.
"""

import os
import xml.etree.ElementTree as ET

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROBOTS = os.path.join(HERE, "..", "robosuite", "robosuite", "models", "assets", "robots")
SRC = os.path.join(ROBOTS, "panda", "robot.xml")
DST = os.path.join(ROBOTS, "fr3", "robot.xml")

