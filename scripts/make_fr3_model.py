HEADER = (
    '<?xml version="1.0" ?>\n'
    "<!-- GENERATED by scripts/make_fr3_model.py; edit that script, not this file.\n"
    "     Franka Research 3: robosuite's Panda structure (../panda/robot.xml), MuJoCo Menagerie's franka_fr3 meshes\n"
    "     (meshes/, MESHES.md), and the joint limits, torque limits and link inertials of franka_description's fr3.urdf\n"
    "     (HSA-UMI/external/franka_ros2/franka_hardware/test/fr3.urdf). See running.md, 'Robots'. -->\n"
)


def main():
    tree = ET.parse(SRC)
    root = tree.getroot()
    root.set("model", "fr3")

    # Assets: drop the Panda's, add Menagerie's
    asset = root.find("asset")
    for child in list(asset):
        asset.remove(child)
    for name, rgba in MATERIALS.items():
        ET.SubElement(asset, "material", name=name, specular="0.5", shininess="0.45", rgba=rgba)
    for link, pieces in VISUALS.items():
        for mesh, _ in pieces:
            ET.SubElement(asset, "mesh", name=mesh, file=f"meshes/{mesh}.obj")
        ET.SubElement(asset, "mesh", name=f"{link}_coll", file=f"meshes/{link}.stl")

    for j in root.iter("joint"):
        lo, hi, _ = LIMITS[j.get("name")]
        j.set("range", f"{lo} {hi}")
    for a in root.iter("motor"):
        eff = LIMITS[a.get("joint")][2]
        a.set("ctrlrange", f"-{eff} {eff}")

    for body in root.iter("body"):
        name = body.get("name")
        if name in INERTIALS:
            mass, com, (ixx, ixy, ixz, iyy, iyz, izz) = INERTIALS[name]
            I = np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])
            w = np.sort(np.linalg.eigvalsh(I))
            assert w[0] > 0 and w[0] + w[1] >= w[2] * (1 - 1e-9), f"{name}: inertia violates the triangle inequality"
            inertial = body.find("inertial")
            inertial.attrib.clear()
            inertial.set("pos", " ".join(f"{c:.10g}" for c in com))
            inertial.set("mass", f"{mass:.10g}")
            inertial.set("fullinertia", " ".join(f"{v:.10g}" for v in (ixx, iyy, izz, ixy, ixz, iyz)))
            # Geometry: Menagerie's visual pieces (robosuite's group 1, no contact) and convex collision hull (group 0)
            geoms = body.findall("geom")
            first = list(body).index(geoms[0])
            for g in geoms:
                body.remove(g)
            new = [
                ET.Element("geom", mesh=mesh, material=mat, type="mesh", contype="0", conaffinity="0", group="1")
                for mesh, mat in VISUALS[name]
            ]
            new.append(ET.Element("geom", type="mesh", group="0", mesh=f"{name}_coll", name=f"{name}_collision"))
            for k, g in enumerate(new):
                body.insert(first + k, g)
        if name == "right_hand":
            body.set("pos", "0 0 0.107")  # fr3_joint8: the flange is 107 mm from link 7 (robosuite's Panda: 0.1065)

    # Menagerie excludes the link0 / link1 contact (their hulls touch at the joint)
    contact = root.find("contact")
    if contact is None:
        contact = ET.SubElement(root, "contact")
    ET.SubElement(contact, "exclude", body1="link0", body2="link1")

    ET.indent(tree, space="  ")
    with open(DST, "w") as f:
        f.write(HEADER + ET.tostring(root, encoding="unicode") + "\n")
    print("wrote", os.path.relpath(DST, HERE))


if __name__ == "__main__":
    main()
